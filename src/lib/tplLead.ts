// ПК: форма слева, заголовок справа; или заголовок сверху, форма снизу; или форма слева, фото эксперта справа. Поля формы в две колонки.
// Все элементы обычные (текст, поле, кнопка, плашка): правится каждая деталь. Поле «во сколько позвонить» открывается при выборе «По времени».
