const SCR:Record<Dev,number>={desktop:820,tablet:952,mobile:780};
const GAPS=[12,8,6];
const CONSENT='☐ Я принимаю условия передачи информации';

/** ряд кнопок-вариантов: короткие в сетку, длинные («Не знаю / нужна консультация») отдельной строкой */
function chips(c:C,x:number,y:number,w:number,a:string[],sel:number,hh=44){
const g=8,fs=14;const it=a.map((s,i)=>({s,i,l:s.length>20}));const sh=it.filter(v=>!v.l),lg=it.filter(v=>v.l);
const mx=Math.max(1,...sh.map(v=>v.s.length));let cc=Math.min(sh.length,4)||1;
while(cc>1&&(w-(cc-1)*g)/cc<mx*fs*.55+8)cc--;
const cw=(w-(cc-1)*g)/cc;let row=0;
sh.forEach((v,j)=>{const r=Math.floor(j/cc),k=j%cc;row=r+1;c.add('btn',x+k*(cw+g),y+r*(hh+g),cw,hh,v.s,{fs,...(v.i===sel?{acc:true}:{})})});
lg.forEach(v=>{c.add('btn',x,y+row*(hh+g),w,hh,v.s,{fs,...(v.i===sel?{acc:true}:{})});row++});
return y+row*(hh+g)-g}

function field(c:C,f:F,x:number,y0:number,w:number,d:Dev,g:number):number{
const sm=d==='mobile'&&g<8,ih=d==='mobile'?(sm?44:48):52,ch=sm?40:44;let y=y0;
const hint=(t:string)=>{y=c.tx(t,x,y,w,13,{b:true})+4};
switch(f.k){
case 'msg':hint(f.q??'Выберите: куда отправить');y=chips(c,x,y,w,f.a,f.sel??0,ch);break;
case 'pick':hint(f.q);y=chips(c,x,y,w,f.a,f.sel??0,ch);break;
case 'tel':hint(f.q??'Введите: телефон');c.add('input',x,y,w,ih,'+7 (___) ___-__-__');y+=ih;break;
case 'mail':hint(f.q??'Введите: e-mail');c.add('input',x,y,w,ih,'name@mail.ru');y+=ih;break;
case 'inp':hint(f.q);c.add('input',x,y,w,ih,f.ph);y+=ih;break;
case 'when':hint('Выберите: когда позвонить');y=chips(c,x,y,w,['Сейчас','По времени'],0,ch)+g;hint('↳ Введите: во сколько позвонить');c.add('input',x,y,w,ih,'Например, завтра в 12:00');y+=ih;break;
case 'range':{const vw=Math.round(w*.4);const qy=c.tx(f.q,x,y,w-vw,13,{b:true});c.tx(f.val,x+w-vw,y,vw,16,{b:true,al:'r'});y=Math.max(qy,y+21)+6;
c.add('rect',x,y+10,w,8,'',{r:4});c.add('btn',x+Math.round(w*.4),y,28,28,'',{acc:true,r:14});y+=28+4;
const ey=c.tx(f.from,x,y,w/2,13);c.tx(f.to,x+w/2,y,w/2,13,{al:'r'});y=ey;break}
case 'file':hint(f.q);c.add('btn',x,y,w,ih,f.t,{fs:14});y+=ih;break;
case 'step':y=c.tx(f.t,x,y,w,13,{b:true})+6;c.add('rect',x,y,w,8,'',{r:4});c.add('btn',x,y,Math.round(w/3),8,'',{acc:true,r:4});y+=8;break;
case 'alt':c.add('btn',x,y,w,44,f.t,{fs:14});y+=44;break}
return y+g}

/** карточка формы: заголовок, поля, кнопка (текст совпадает с заголовком), галочка, что будет после отправки */
function card(c:C,s:Spec,x:number,y:number,w:number,d:Dev,k:number):number{
const m=d==='mobile',pad=m?16:28,iw=w-2*pad,g=GAPS[k],top=y;let yy=y+pad;
yy=c.tx(s.form.title,x+pad,yy,iw,m?18:22,{b:true})+(k?6:12);
for(const f of s.form.f)yy=field(c,f,x+pad,yy,iw,d,g);
const bh=m?(k>1?48:52):56;c.add('btn',x+pad,yy,iw,bh,s.form.btn,{fs:m?15:16,acc:true});yy+=bh+8;
yy=c.tx(CONSENT,x+pad,yy,iw,13)+4;
yy=c.tx('✓ '+s.form.note,x+pad,yy,iw,13);
const ch=r4(yy-top+pad);c.els.unshift({id:uid(),t:'rect',x,y:top,w,h:ch,text:''});return top+ch}

/** ряд «артефакт + плашки»: обложка/фото слева, справа бейдж, дефицит и таймер */
function artRow(c:C,s:Spec,x:number,y:number,w:number,ah:number){
const items=[...(s.badge?[s.badge]:[]),...(s.press??[])];const iw=Math.round(w*.62);
const ph=items.length?Math.min(56,Math.floor((ah-(items.length-1)*8)/items.length)):0;
const need=items.length*56+(items.length-1)*8;const hh=Math.max(ah,items.length?need:0);
c.add('img',x,y,iw,hh,s.art);
items.forEach((t,i)=>{if(ph>=40||hh>=need)c.plate(x+iw+16,y+i*64,w-iw-16,56,t,14,true,'c')});
return y+hh}

const lines=(c:C,a:string[],x:number,y:number,w:number,fs:number,gap:number)=>{for(const t of a)y=c.tx('✓ '+t,x,y,w,fs)+gap;return y};

function left(c:C,s:Spec,x:number,w:number,art=true):number{let y=0;
y=c.tx(s.h,x,y,w,32,{b:true})+14;
if(s.sub)y=c.tx(s.sub,x,y,w,18)+16;
y=lines(c,s.ben,x,y,w,16,10)+6;
if(s.gifts){const g=12,pw=(w-2*g)/3;s.gifts.forEach((t,i)=>c.plate(x+i*(pw+g),y,pw,64,t,14,true,'c'));y+=64+16}
if(art)y=artRow(c,s,x,y,w,190);
return y}
const shiftAll=(a:Out['els'],dy:number)=>{for(const e of a)e.y=Math.round(e.y+dy)};

function splitD(s:Spec):Out{const cl=ctx(),cr=ctx();const fx=s.flip;const lx=fx?720:120,cx=fx?120:780;
const hl=left(cl,s,lx,600);let hr=0;
for(let k=0;k<3;k++){const t=ctx();hr=card(t,s,cx,0,540,'desktop',k);if(hr<=756||k===2){cr.els.push(...t.els);break}}
shiftAll(cl.els,Math.max(32,r4((SCR.desktop-hl)/2)));shiftAll(cr.els,Math.max(32,r4((SCR.desktop-hr)/2)));
const els=[...cr.els,...cl.els];const h=Math.max(SCR.desktop,...els.map(e=>e.y+e.h+32));return{h:r4(h),els}}

function personD(s:Spec):Out{const c=ctx();const cl=ctx();let y=0;
y=cl.tx(s.h,120,y,680,32,{b:true})+14;y=lines(cl,s.ben,120,y,680,16,10)+10;
let end=0;for(let k=0;k<3;k++){const t=ctx();end=card(t,s,120,y,560,'desktop',k);if(end<=756||k===2){cl.els.push(...t.els);break}}
const dy=Math.max(32,r4((SCR.desktop-end)/2));shiftAll(cl.els,dy);
c.els.push(...cl.els);c.add('img',860,32,460,756,s.art);
if(s.press?.[0])c.plate(884,52,280,64,s.press[0],14,true,'c');
if(s.person)c.plate(884,692,412,80,s.person,14,true,'c');
return{h:SCR.desktop,els:c.els}}

function barD(s:Spec):Out{const c=ctx(),cl=ctx();
const yl=left(cl,s,120,700,false);
const ax=880,aw=440;let ay=0;cl.add('img',ax,ay,aw,300,s.art);ay=300+12;
for(const t of [...(s.badge?[s.badge]:[]),...(s.press??[])]){cl.plate(ax,ay,aw,52,t,14,true,'c');ay+=60}
const by=Math.max(yl,ay)+28;
const pad=28,iw=1200-2*pad,bw=400,n=s.form.f.length,wi=(iw-bw-16*n)/n;
let y=by+pad;y=cl.tx(s.form.title,120+pad,y,iw,22,{b:true})+12;
s.form.f.forEach((f,i)=>{const t=ctx();field(t,f,120+pad+i*(wi+16),y,wi,'desktop',0);cl.els.push(...t.els)});
cl.add('btn',120+pad+n*(wi+16),y+24,bw,52,s.form.btn,{fs:16,acc:true});y+=24+52+10;
y=cl.tx(CONSENT,120+pad,y,iw,13)+4;y=cl.tx('✓ '+s.form.note,120+pad,y,iw,13);
const ch=r4(y-by+pad);cl.els.push({id:uid(),t:'rect',x:120,y:by,w:1200,h:ch,text:''});
const bottom=by+ch;const dy=Math.max(24,r4((SCR.desktop-bottom)/2));
// карточка-фон должна лежать под полями
const bg=cl.els.pop()!;cl.els.unshift(bg);shiftAll(cl.els,dy);
c.els.push(...cl.els);return{h:Math.max(SCR.desktop,r4(bottom+dy+24)),els:c.els}}

/** планшет и мобилка: стопка; если не влезает в экран, по шагам убираем обложку, выгоды, подзаголовок */
function stackL(s:Spec,d:Dev,lvl:number):Out{const c=ctx(),m=d==='mobile',W=FW[d],X=m?20:48,w=W-2*X;let y=m?20:36;
y=c.tx(m&&s.hm?s.hm:s.h,X,y,w,m?20:28,{b:true})+12;
if(!m&&s.sub&&lvl<3)y=c.tx(s.sub,X,y,w,16)+10;
if(lvl<2){if(m)y=c.tx(s.bm.map(a=>'✓ '+a).join('   '),X,y,w,14,{b:true})+10;else y=lines(c,s.ben,X,y,w,15,6)+4}
if(s.gifts&&lvl<2)y=c.tx('Подарки: '+s.gifts.join(' · '),X,y,w,14,{b:true})+10;
if(lvl<1)y=artRow(c,s,X,y,w,m?96:128)+12;
else if(s.press?.length&&lvl<2)y=c.tx('● '+s.press[0],X,y,w,13,{b:true})+10;
const end=card(c,s,X,y,w,d,Math.min(lvl,2));
return{h:r4(Math.max(m?560:640,end+(m?20:36))),els:c.els}}
function stack(s:Spec,d:Dev):Out{let o=stackL(s,d,0);for(let l=1;l<=3&&o.h>SCR[d];l++)o=stackL(s,d,l);return o}
const build=(s:Spec)=>(d:Dev):Out=>d!=='desktop'?stack(s,d):s.look==='bar'?barD(s):s.look==='person'?personD(s):splitD(s);

