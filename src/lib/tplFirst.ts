const SCR:Record<Dev,number>={desktop:820,tablet:952,mobile:780};
/** стопка для планшета и мобилки */
function stack(parts:Part[],dev:Dev):Out{const c=ctx();const m=dev==='mobile';const W=FW[dev];const X=m?20:48;const w=W-2*X;let y=m?20:48;let sticky='';
const bw=m?w:Math.min(w,420);
for(const p of parts){
if('m' in p&&p.m===false&&m)continue;
switch(p.k){
case 'eb':y=c.tx(p.t,X,y,w,14)+4;break;
case 'h1':y=c.tx(p.t,X,y,w,m?28:36,{b:true})+8;break;
case 'sub':y=c.tx(p.t,X,y,w,m?16:20)+8;break;
case 'lead':y=c.tx(p.t,X,y,w,16)+12;break;
case 'note':y=c.tx(p.t,X,y,w,14)+8;break;
case 'cta':if(m)sticky=p.t;else{c.add('btn',X,y,bw,56,p.t,{fs:16,acc:true});y+=56+12}break;
case 'img':{const ih=m?112:136;c.add('img',X,y,w,ih,p.t);y+=ih+12;break}
case 'badge':{c.add('rect',X,y,m?w:Math.min(w,360),48,p.t,{fs:14});y+=48+12;break}
case 'chips':{if(m){y=c.tx('Для: '+p.a.join(' · '),X,y,w,14,{b:true})+8}else{const g=12,cw=(w-2*g)/3;p.a.forEach((a,i)=>c.add('rect',X+i*(cw+g),y,cw,56,a,{fs:14}));y+=56+12}break}
case 'card':{const pad=m?16:24,iw=w-2*pad;const top=y;let yy=y+pad;
yy=c.tx(p.title,X+pad,yy,iw,m?18:22,{b:true})+6;
for(const l of p.lines??[])yy=c.tx(l,X+pad,yy,iw,m?14:16)+4;
yy+=6;
if(p.inp){c.add('input',X+pad,yy,iw,m?48:56,p.inp);yy+=(m?48:56)+8}
if(m)sticky=p.btn;else{c.add('btn',X+pad,yy,Math.min(iw,400),56,p.btn,{fs:16,acc:true});yy+=56+8}
if(p.note)yy=c.tx(p.note,X+pad,yy,iw,12)+4;
const ch=r8(yy-top+pad-8);c.els.unshift({id:uid(),t:'rect',x:X,y:top,w,h:ch,text:''});y=top+ch+12;break}
case 'ben':{p.a.forEach(([t,d])=>{const ic=m?32:40;const tw=w-(ic+40);const ty=th(t,m?14:16,tw,true);const dy=d&&!m?th(d,14,tw):0;const hh=r8(Math.max(m?52:64,16+ty+(dy?4+dy:0)+16));
c.add('rect',X,y,w,hh);c.add('img',X+16,y+(hh-ic)/2,ic,ic,'Иконка');
let ty0=y+(hh-(ty+(dy?4+dy:0)))/2;ty0=c.tx(t,X+16+ic+12,ty0,tw,m?14:16,{b:true})+4;if(dy)c.tx(d,X+16+ic+12,ty0,tw,14);
y+=hh+(m?8:12)});break}
}}
let h=0;
if(m){const bh=96;const need=r8(y+8+bh);h=Math.max(SCR.mobile,need);const by=h-bh;
c.add('rect',0,by,W,bh);c.add('text',X,by+6,w,16,'Закреплено внизу экрана',{fs:11});
c.add('btn',X,by+26,w-2*44-16,52,sticky,{fs:14,acc:true});
c.add('rect',X+w-2*44-8,by+26,44,52,'TG',{fs:14});c.add('rect',X+w-44,by+26,44,52,'WA',{fs:14})}
else h=Math.max(SCR[dev],r8(y+48));
return{h,els:c.els}}

