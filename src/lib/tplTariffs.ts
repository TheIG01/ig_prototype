 s.plans.forEach((p,i)=>{const x=LX+i*(w+g);let yy=top+24;c.add('img',x+24,yy,64,64,'Иконка',{r:16});yy+=80;
  yy=c.tx(p.n,x+24,yy,w-48,20,{b:true})+8;yy=c.tx(p.pts[0],x+24,yy,w-48,15)+16;
  yy=c.tx(p.p,x+24,yy,w-48,28,{b:true})+16;bot=Math.max(bot,yy)});
